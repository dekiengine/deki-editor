#include <deki-profiling-hooks/ProfilingHooks.h>

#ifdef _WIN32
#include <intrin.h>
#include <Windows.h>
#endif

// The editor's callbacks; null until ProfilingSetCallbacks.
static volatile ProfileEnterCallback s_EnterCallback = nullptr;
static volatile ProfileExitCallback s_ExitCallback = nullptr;

extern "C"
{
    // The editor sets its profiling callbacks here.
    void ProfilingSetCallbacks(ProfileEnterCallback enter, ProfileExitCallback exit)
    {
        s_EnterCallback = enter;
        s_ExitCallback = exit;
    }

    // Called by the _penter hook of instrumented project DLLs (generated by
    // BuildFileGenerator).
    void DekiEditorProfileEnter(void* returnAddress)
    {
        // Not set yet during early DLL initialization.
        if (!s_EnterCallback)
        {
            return;
        }

// SEH is MSVC-only; MinGW/GCC has no __try/__except.
#ifdef _MSC_VER
        __try
        {
            s_EnterCallback(returnAddress);
        }
        __except (EXCEPTION_EXECUTE_HANDLER)
        {
            // Silently ignore exceptions in profiling hooks
        }
#else
        s_EnterCallback(returnAddress);
#endif
    }

    // Called by the _pexit hook of instrumented project DLLs.
    void DekiEditorProfileExit()
    {
        // Not set yet during early DLL initialization.
        if (!s_ExitCallback)
        {
            return;
        }

// SEH is MSVC-only; MinGW/GCC has no __try/__except.
#ifdef _MSC_VER
        __try
        {
            s_ExitCallback();
        }
        __except (EXCEPTION_EXECUTE_HANDLER)
        {
            // Silently ignore exceptions in profiling hooks
        }
#else
        s_ExitCallback();
#endif
    }

// MSVC /Gh /GH hooks, so anything built with /Gh /GH links. These do nothing;
// generated project code defines its own that call the functions above. MSVC
// only: see the note on the declarations in ProfilingHooks.h.
#ifdef _MSC_VER
#pragma runtime_checks("", off)

    void __cdecl _penter()
    {
        // Empty - do absolutely nothing
    }

    void __cdecl _pexit()
    {
        // Empty - do absolutely nothing
    }

#pragma runtime_checks("", restore)
#endif  // _MSC_VER
}
