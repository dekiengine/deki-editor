#!/usr/bin/env bash
# Compiles src/render/shaders/text.frag into src/render/TextShaders.h: SPIR-V
# for Vulkan and DXBC for Direct3D 12, one shader per colour channel. Run it
# from Git Bash on Windows after editing the shader. glslangValidator and
# spirv-cross run inside WSL (sudo apt install glslang-tools spirv-cross);
# fxc comes with the Windows SDK. Metal has no build here: on macOS the editor
# draws greyscale text, as macOS itself does.
set -euo pipefail
export MSYS2_ARG_CONV_EXCL='*'  # Git Bash would rewrite the /mnt/... paths given to wsl
root=$(cd "$(dirname "$0")/.." && pwd)
src=$root/src/render/shaders/text.frag
out=$root/src/render/TextShaders.h
fxc=${FXC:-$(ls "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe | tail -1)}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

wslpath_of() { wsl -e wslpath -a "$(cygpath -w "$1")"; }
wsrc=$(wslpath_of "$src")
wtmp=$(wslpath_of "$tmp")

array() {  # array <name> <file>
    echo "static const uint8_t $1[] = {"
    od -An -v -tx1 "$2" | sed -e 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g' -e 's/^/    /' -e 's/, $/,/'
    echo "};"
}

{
    echo "// Generated by tools/build-text-shaders.sh from shaders/text.frag. Do not edit."
    echo "#pragma once"
    echo
    echo "#include <cstdint>"
    for channel in 0 1 2; do
        pass=channel$channel
        wsl -e glslangValidator -V -S frag -DCHANNEL=$channel -o "$wtmp/$pass.spv" "$wsrc" >/dev/null
        wsl -e spirv-cross "$wtmp/$pass.spv" --hlsl --shader-model 51 --output "$wtmp/$pass.hlsl"
        "$fxc" /nologo /T ps_5_1 /E main /O3 /Fo "$(cygpath -w "$tmp/$pass.dxbc")" \
            "$(cygpath -w "$tmp/$pass.hlsl")" >/dev/null 2>&1
        echo
        array "kText_${pass}_spirv" "$tmp/$pass.spv"
        array "kText_${pass}_dxbc" "$tmp/$pass.dxbc"
    done
} >"$out"
echo "wrote $out"
